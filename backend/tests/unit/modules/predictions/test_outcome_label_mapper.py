from __future__ import annotations

import pytest

from modules.predictions.application.outcome_label_mapper import (
    MARKET_OUTCOME_LABELS,
    map_generic_distribution_to_real_labels,
    map_generic_value_to_real_label,
    real_label_is_positive,
    real_outcome_is_positive,
)


@pytest.mark.parametrize(
    "market_key,positive_label,negative_label",
    [
        ("football.both_teams_to_score", "YES", "NO"),
        ("football.total_goals_over_under", "OVER", "UNDER"),
        ("football.home_team_total_goals", "OVER", "UNDER"),
        ("basketball.moneyline", "HOME", "AWAY"),
        ("baseball.moneyline", "HOME_WIN", "AWAY_WIN"),
        ("table_tennis.match_winner", "HOME_WIN", "AWAY_WIN"),
    ],
)
def test_map_generic_value_to_real_label_covers_all_six_markets(market_key, positive_label, negative_label):
    assert map_generic_value_to_real_label(market_key, "positive") == positive_label
    assert map_generic_value_to_real_label(market_key, "negative") == negative_label


def test_map_generic_value_to_real_label_leaves_uncovered_market_unchanged():
    assert map_generic_value_to_real_label("football.match_result", "positive") == "positive"
    assert map_generic_value_to_real_label("football.correct_score", "0.6234") == "0.6234"


def test_map_generic_value_to_real_label_leaves_non_generic_values_unchanged():
    """A TOTAL-kind market's raw regression-number string isn't "positive"/"negative" — must
    pass through untouched even for a market_key this table does cover."""
    assert map_generic_value_to_real_label("football.total_goals_over_under", "1.2345") == "1.2345"


@pytest.mark.parametrize(
    "market_key,positive_label,negative_label",
    [
        ("football.both_teams_to_score", "YES", "NO"),
        ("basketball.moneyline", "HOME", "AWAY"),
    ],
)
def test_real_label_is_positive_reads_real_labels(market_key, positive_label, negative_label):
    assert real_label_is_positive(market_key, positive_label) is True
    assert real_label_is_positive(market_key, negative_label) is False


def test_real_label_is_positive_still_recognizes_legacy_generic_values():
    """Safety net across a rolling deploy — a prediction generated by an old process instance
    right before Phase 2's code shipped must still evaluate correctly."""
    assert real_label_is_positive("football.both_teams_to_score", "positive") is True
    assert real_label_is_positive("football.both_teams_to_score", "negative") is False


def test_real_label_is_positive_returns_none_for_uncovered_market():
    assert real_label_is_positive("football.match_result", "YES") is None


def test_real_label_is_positive_returns_none_for_unrecognized_value():
    assert real_label_is_positive("football.both_teams_to_score", "MAYBE") is None


def test_generation_and_evaluation_label_tables_agree_on_every_binary_market():
    """The market_outcome_registry catalog's resolver_key entries and this module's coverage must
    name the same six binary (positive/negative-polarity) markets — drift here would mean
    generation and evaluation silently disagree on what a market's real labels are.

    Excludes three-way markets (Milestone 9.2 Phase 3, e.g. football.match_winner) and grid markets
    (2026-08-06, football.correct_score): both have a resolver_key too, but resolve via
    THREE_WAY_MARKET_RESOLVERS/GRID_MARKET_RESOLVERS' direct label equality, not this module's
    positive/negative pair — neither ever belongs in MARKET_OUTCOME_LABELS."""
    from modules.predictions.application.outcome_resolution_service import (
        GRID_MARKET_RESOLVERS,
        THREE_WAY_MARKET_RESOLVERS,
    )
    from modules.predictions.domain.market_outcome_registry import MARKET_OUTCOME_CATALOG

    catalog_resolver_keys = {spec.resolver_key for spec in MARKET_OUTCOME_CATALOG.values() if spec.resolver_key}
    binary_resolver_keys = catalog_resolver_keys - set(THREE_WAY_MARKET_RESOLVERS.keys()) - set(GRID_MARKET_RESOLVERS.keys())
    assert binary_resolver_keys == set(MARKET_OUTCOME_LABELS.keys())


def test_map_generic_distribution_to_real_labels_covers_a_binary_market():
    assert map_generic_distribution_to_real_labels(
        "football.both_teams_to_score", {"positive": 0.7, "negative": 0.3}
    ) == {"YES": 0.7, "NO": 0.3}


def test_map_generic_distribution_to_real_labels_leaves_uncovered_market_unchanged():
    distribution = {"positive": 0.6, "negative": 0.4}
    assert map_generic_distribution_to_real_labels("football.match_result", distribution) == distribution


def test_map_generic_distribution_to_real_labels_passes_through_already_real_keys():
    """The ordinal/Poisson predictors already emit real labels — this must be a no-op for them,
    same as `map_generic_value_to_real_label` for a non-generic value."""
    distribution = {"HOME_WIN": 0.5, "DRAW": 0.25, "AWAY_WIN": 0.25}
    assert map_generic_distribution_to_real_labels("football.match_winner", distribution) == distribution


def test_map_generic_distribution_to_real_labels_handles_empty_distribution():
    assert map_generic_distribution_to_real_labels("football.both_teams_to_score", {}) == {}


class TestRealOutcomeIsPositive:
    """Shared by the Dataset Builder (training labels) and Calibration Fitting (calibration
    samples) — both need the real outcome's polarity, not what was predicted."""

    def test_matching_positive_claim_is_a_positive_outcome(self):
        assert real_outcome_is_positive("football.both_teams_to_score", "YES", error=0.0) is True

    def test_matching_negative_claim_is_a_negative_outcome(self):
        assert real_outcome_is_positive("football.both_teams_to_score", "NO", error=0.0) is False

    def test_mismatched_positive_claim_flips_to_a_negative_outcome(self):
        assert real_outcome_is_positive("football.both_teams_to_score", "YES", error=1.0) is False

    def test_mismatched_negative_claim_flips_to_a_positive_outcome(self):
        assert real_outcome_is_positive("football.both_teams_to_score", "NO", error=1.0) is True

    def test_recognizes_legacy_generic_values(self):
        assert real_outcome_is_positive("football.both_teams_to_score", "positive", error=0.0) is True
        assert real_outcome_is_positive("football.both_teams_to_score", "negative", error=1.0) is True

    def test_returns_none_for_a_market_with_no_binary_polarity(self):
        assert real_outcome_is_positive("football.match_winner", "HOME_WIN", error=0.0) is None

    def test_returns_none_when_error_was_never_recorded(self):
        assert real_outcome_is_positive("football.both_teams_to_score", "YES", error=None) is None
