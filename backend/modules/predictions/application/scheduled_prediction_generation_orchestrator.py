"""Scheduled Prediction Generation Orchestrator.

Real gap found live (2026-08-26): `ingestion.sync_upcoming_fixtures` (football-data.org) already
runs on its own Beat schedule and correctly ingests real upcoming fixtures — confirmed live, 370
genuinely-future SCHEDULED Premier League fixtures landed in the database from that sync alone.
But ingesting a fixture and generating a prediction for it are two different steps
(`PredictionCacheService.get_or_generate` is the second one), and nothing ever called the second
step automatically — every prediction that has ever existed in this system was generated by a
manual/admin API call. `featured-intelligence` (the public landing page) was therefore stuck
showing its own honest empty state even once real upcoming fixtures existed, because there was
genuinely nothing to publish yet.

This orchestrator is that missing loop, meant to be run periodically
(`modules/predictions/infrastructure/celery/tasks.py`): for every PRODUCTION market, generate (or
refresh) a prediction for every fixture of that market's sport kicking off within
`lookahead_hours` — close enough to kickoff that engineered features (form, injuries, structured
intelligence) have had a real chance to be computed, per this codebase's own existing pattern (see
`STRUCTURED_INTEL_INTERVAL_SECONDS`'s docstring, `beat_schedule.py`).

Reuses `PredictionCacheService.get_or_generate` exactly as the manual admin/API path does —
same caching (a prediction generated within the last `cache_ttl_seconds` is returned as-is, not
regenerated), same confidence-gated auto-publish, same audit trail. This orchestrator adds no new
generation logic of its own; it only supplies the caller loop nothing else ever did.

One (fixture, market) pair's failure — most commonly `MissingRequiredFeatureError` (a required
feature genuinely has no verified pre-match value yet) or `NoChampionModelError` (the market has
no trained model to serve) — is captured and skipped, never allowed to stop the sweep from
reaching every other pair, matching `ScheduledRetrainingOrchestrator`'s own per-market isolation
posture.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta

from modules.features.domain.value_objects import EntityType
from modules.predictions.application.feature_market_mapping_service import MissingRequiredFeatureError
from modules.predictions.application.prediction_cache_service import MarketNotFoundError, PredictionCacheService
from modules.predictions.application.prediction_context_builder import MarketNotInProductionError, NoChampionModelError
from modules.predictions.domain.entities import MarketDefinition
from modules.predictions.domain.value_objects import MarketStatus, PredictionStatus
from modules.predictions.ports.repositories import MarketRepositoryPort
from modules.sports.domain.value_objects import SportCode
from modules.sports.ports.repositories import FixtureRepositoryPort, SportRepositoryPort

SYSTEM_ACTOR = "scheduled-prediction-generation"

# A week's lookahead is generous enough to keep the landing page (and any other featured-
# intelligence consumer) populated well before kickoff, while staying short enough that every
# fixture in scope is close enough to real for its engineered features (recent form, structured
# intelligence) to actually be computed — the same "close to kickoff, not months out" posture
# `sync_upcoming_structured_intelligence`'s own LINEUP_PREMATCH_WINDOW_MINUTES already takes,
# just at a coarser (day-scale, not minute-scale) grain appropriate for a quantitative prediction
# rather than an official lineup announcement.
DEFAULT_GENERATION_LOOKAHEAD_HOURS = 168


def _ensure_aware(dt: datetime, reference: datetime) -> datetime:
    """Same fix as `SyncOrchestrator`'s own `_ensure_aware` — SQLite/aiosqlite drops tzinfo on
    read-back (docs/decisions.md ADR-007); a naive value is assumed UTC and stamped to match
    `reference`'s awareness before comparison."""
    if dt.tzinfo is None and reference.tzinfo is not None:
        return dt.replace(tzinfo=reference.tzinfo)
    return dt


@dataclass(frozen=True)
class GenerationOutcome:
    fixture_id: str
    market_key: str
    status: str
    """"published" | "draft" (generated but below the market's confidence threshold) |
    "skipped" (a real, expected gap — see class docstring)."""
    reason: str | None = None


@dataclass
class ScheduledPredictionGenerationOrchestrator:
    cache: PredictionCacheService
    markets: MarketRepositoryPort
    sports: SportRepositoryPort
    fixtures: FixtureRepositoryPort
    lookahead_hours: int = DEFAULT_GENERATION_LOOKAHEAD_HOURS

    async def run(self, now: datetime) -> list[GenerationOutcome]:
        """The periodic sweep a Celery beat task calls: every PRODUCTION market, every fixture of
        that market's sport due within `lookahead_hours`."""
        markets_by_sport: dict[str, list[MarketDefinition]] = {}
        for market in await self.markets.list_by_status(MarketStatus.PRODUCTION):
            markets_by_sport.setdefault(market.sport_code, []).append(market)

        outcomes: list[GenerationOutcome] = []
        for sport_code, markets in markets_by_sport.items():
            sport = await self.sports.get_by_code(SportCode(sport_code))
            if sport is None:
                continue
            fixtures = await self.fixtures.list_by_sport(sport.id, status="scheduled")
            for fixture in fixtures:
                if not self._within_window(fixture.scheduled_at, now):
                    continue
                subject_ref = str(fixture.id)
                for market in markets:
                    outcomes.append(await self._generate_one(subject_ref, market, now))
        return outcomes

    def _within_window(self, scheduled_at: datetime, now: datetime) -> bool:
        scheduled_at = _ensure_aware(scheduled_at, now)
        return now < scheduled_at <= now + timedelta(hours=self.lookahead_hours)

    async def _generate_one(self, subject_ref: str, market: MarketDefinition, now: datetime) -> GenerationOutcome:
        try:
            prediction = await self.cache.get_or_generate(
                market.market_key, EntityType.FIXTURE, subject_ref, subject_ref, now, actor=SYSTEM_ACTOR,
            )
        except (MarketNotFoundError, MarketNotInProductionError, NoChampionModelError, MissingRequiredFeatureError) as exc:
            # Honest, expected gaps — a real prediction just isn't buildable yet (no champion model,
            # a required feature hasn't verified a pre-match value, etc.), never treated as a bug.
            return GenerationOutcome(fixture_id=subject_ref, market_key=market.market_key, status="skipped", reason=str(exc))
        except Exception as exc:  # noqa: BLE001 — one pair's failure must never stop the sweep
            return GenerationOutcome(
                fixture_id=subject_ref, market_key=market.market_key, status="skipped",
                reason=f"unexpected error: {exc}",
            )
        status = "published" if prediction.status is PredictionStatus.PUBLISHED else "draft"
        return GenerationOutcome(fixture_id=subject_ref, market_key=market.market_key, status=status)
